#!/usr/bin/env node
/**
 * What a packaged desktop app actually contains (electron-desktop-v1 §2, §6): grouped ASAR paths,
 * unpacked native addons with SHA-256, bundled fonts, signing state, the build identity and a check
 * that nothing private or incidental was shipped (owner media, keys, tokens, player stores, `.env`).
 *
 *   node tools/hapa/desktop-manifest.mjs [--app <path to .app>] [--out file.json]
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, resolve, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync, spawnSync } from 'node:child_process';
import * as asar from '@electron/asar';

const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i > 0 ? process.argv[i + 1] : d; };
const app = resolve(arg('app', 'out/Hapa Versus-darwin-arm64/Hapa Versus.app'));
const res = join(app, 'Contents', 'Resources');
const archive = join(res, 'app.asar');
const sha = (f) => createHash('sha256').update(readFileSync(f)).digest('hex');
const files = asar.listPackage(archive, { isPack: false }).map((p) => p.replace(/\\/g, '/'));
const fileList = files.filter((p) => { try { const st = asar.statFile(archive, p.replace(/^\//, ''), false); return !st.files; } catch { return false; } });
const group = (p) => { const s = p.split('/'); if (s[1] === 'node_modules') return `/node_modules/${s[2].startsWith('@') ? `${s[2]}/${s[3]}` : s[2]}`; if (s[1] === 'src') return `/src/${s[2]}/${s[3] ?? ''}`.replace(/\/$/, ''); return `/${s[1]}${s.length > 2 && s[1] !== 'dist' ? '' : s[2] ? `/${s[2]}` : ''}`; };
const groups = {};
for (const f of fileList) groups[group(f)] = (groups[group(f)] ?? 0) + 1;
const walk = (d) => readdirSync(d).flatMap((n) => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
const unpacked = existsSync(join(res, 'app.asar.unpacked')) ? walk(join(res, 'app.asar.unpacked')).map((f) => ({ path: relative(join(res, 'app.asar.unpacked'), f), bytes: statSync(f).size, sha256: sha(f) })) : [];
const forbidden = [/\/dist\/renditions\//, /identity\.json$/, /transport\.json$/, /owners\.json$/, /\.env/, /api-token/, /operator\.token/, /\.key$/, /\/\.data\//, /\/reference_documents\//, /\/vendor\/lumina\//, /\/docs\//];
const violations = fileList.filter((f) => forbidden.some((r) => r.test(f)));
let build = null;
try { build = JSON.parse(asar.extractFile(archive, 'desktop/build-info.json').toString()); } catch { /* none */ }
let network = null;
try { network = JSON.parse(asar.extractFile(archive, 'desktop/network.json').toString()); } catch { /* none */ }
const plist = readFileSync(join(app, 'Contents', 'Info.plist'), 'utf8');
const key = (k) => (plist.match(new RegExp(`<key>${k}</key>\\s*<string>([^<]*)</string>`)) ?? [])[1] ?? null;
const run = (cmd, args) => { try { return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim(); } catch (e) { return (e.stderr || e.stdout || e.message).toString().trim(); } };
const sig = (() => { const r = spawnSync('codesign', ['-dv', '--verbose=2', app], { encoding: 'utf8' }); return `${r.stdout}\n${r.stderr}`; })();
const manifest = {
  schema: 'hapa-versus-desktop-content/v1',
  app: { bundleId: key('CFBundleIdentifier'), version: key('CFBundleShortVersionString'), executable: key('CFBundleExecutable'), electron: (readFileSync(join(app, 'Contents', 'Frameworks', 'Electron Framework.framework', 'Resources', 'Info.plist'), 'utf8').match(/<key>CFBundleVersion<\/key>\s*<string>([^<]*)/) ?? [])[1] ?? null },
  build,
  asar: { sha256: sha(archive), bytes: statSync(archive).size, files: fileList.length },
  groups: Object.fromEntries(Object.entries(groups).sort()),
  fonts: fileList.filter((f) => /\.(woff2?|ttf)$/.test(f)).map((f) => f.split('/').pop().replace(/-[A-Za-z0-9_]{8}\.(woff2?)$/, '.$1')).filter((v, i, a) => a.indexOf(v) === i),
  unpackedNatives: unpacked,
  networkConfig: network?.networks ?? null,
  excluded: { checked: forbidden.map(String), violations },
  signing: { adhoc: /flags=0x[0-9a-f]*\(adhoc/.test(sig) || /Signature=adhoc/.test(sig), teamIdentifier: (sig.match(/TeamIdentifier=(.*)/) ?? [])[1] ?? null, identifier: (sig.match(/Identifier=(.*)/) ?? [])[1] ?? null, deepVerify: run('codesign', ['--verify', '--deep', '--strict', app]) === '' ? 'valid' : 'invalid', gatekeeper: run('spctl', ['--assess', '--type', 'execute', app]).replace(/^.*: /, '') || 'accepted' },
  starterContent: {
    included: ['procedural unit kit, scenery and fallback Card faces (code)', 'Luminati engine runtime compiled into dist/ (MIT; see engine-runtime-manifest.json)', 'three.js (MIT, compiled into dist/)', 'fonts above (SIL OFL via @fontsource)', 'app icon generated by tools/hapa/make-icon.py'],
    notIncluded: ['Card renditions from public/renditions (owner media; excluded by the allowlist)', 'Red renderer/Avatar snapshot (awaits an approved distribution; Harbor serves it when configured)', 'music libraries, voice, models, Harness, Overwind, Second Brain (optional owners)'],
  },
};
const out = arg('out');
if (out) writeFileSync(resolve(out), JSON.stringify(manifest, null, 1) + '\n');
console.log(JSON.stringify({ files: manifest.asar.files, asar: manifest.asar.sha256.slice(0, 16), natives: unpacked.length, violations: violations.length, signing: manifest.signing, build: build?.source?.slice(0, 8) }));
